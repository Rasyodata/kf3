let CURRENT_LANG = localStorage.getItem('sahapro_lang') || 'tr';
function L(key) {
  const l = I18N[CURRENT_LANG] || I18N.tr;
  return (key in l) ? l[key] : (I18N.tr[key] !== undefined ? I18N.tr[key] : key);
}
function setLang(code) {
  if (!LANGS[code]) return;
  CURRENT_LANG = code;
  localStorage.setItem('sahapro_lang', code);
  document.documentElement.lang = code;
  document.documentElement.dir = LANGS[code].dir;
}
function initLang() {
  document.documentElement.lang = CURRENT_LANG;
  document.documentElement.dir = (LANGS[CURRENT_LANG] || LANGS.tr).dir;
}
